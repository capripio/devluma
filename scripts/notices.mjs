// Generates THIRD_PARTY_NOTICES.md and a CycloneDX SBOM (sbom/devluma.cdx.json) for what
// ships in the installer: Rust crates reachable through *normal* dependencies on
// x86_64-pc-windows-msvc (not dev/build-only), and production npm packages bundled into the
// frontend. License texts are copied from each package's own LICENSE/COPYING/NOTICE files.
//
// Usage: node scripts/notices.mjs   (run before `cargo tauri build`; output is committed)

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const run = (cmd, args, cwd = root) =>
  execFileSync(cmd, args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    shell: process.platform === "win32",
  });

// ---- Rust ----------------------------------------------------------------------------
const meta = JSON.parse(
  run(
    "cargo",
    ["metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"],
    join(root, "src-tauri"),
  ),
);
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const shipped = new Set();
const queue = [meta.resolve.root];
while (queue.length) {
  const id = queue.pop();
  if (shipped.has(id)) continue;
  shipped.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
  }
}
const crates = [...shipped]
  .map((id) => byId.get(id))
  .filter((p) => p && p.source) // registry/git crates, not Devluma itself
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;
function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => {
      try {
        return { file: f, text: readFileSync(join(dir, f), "utf8").trim() };
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

// ---- npm -----------------------------------------------------------------------------
const npmByLicense = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"]));
const npm = Object.entries(npmByLicense)
  .flatMap(([license, pkgs]) =>
    pkgs.flatMap((p) =>
      p.versions.map((v, i) => ({
        name: p.name,
        version: v,
        license,
        path: p.paths[i] ?? p.paths[0],
        homepage: p.homepage,
      })),
    ),
  )
  .sort((a, b) => a.name.localeCompare(b.name));

// ---- Output --------------------------------------------------------------------------
const entries = [
  ...crates.map((c) => ({
    ecosystem: "cargo",
    name: c.name,
    version: c.version,
    license: c.license ?? "(see license file)",
    url: c.repository ?? c.homepage ?? `https://crates.io/crates/${c.name}`,
    texts: licenseTexts(dirname(c.manifest_path)),
    purl: `pkg:cargo/${c.name}@${c.version}`,
  })),
  ...npm.map((p) => ({
    ecosystem: "npm",
    name: p.name,
    version: p.version,
    license: p.license,
    url: p.homepage ?? `https://www.npmjs.com/package/${p.name}`,
    texts: licenseTexts(p.path),
    purl: `pkg:npm/${p.name.replace("@", "%40")}@${p.version}`,
  })),
];

const missing = entries.filter((e) => e.texts.length === 0);
let md = `# Third-party notices\n\nDevluma includes the following open-source components (${entries.length}: ${crates.length} Rust crates, ${npm.length} npm packages). Generated by \`scripts/notices.mjs\`; do not edit by hand.\n\nPackages that Devluma downloads for you at install time (PHP, Nginx, Apache, MariaDB, PostgreSQL, MongoDB, Node.js, Python, Mailpit) are not part of Devluma; their licenses are listed in \`docs/catalog-review.md\` and shipped with each package.\n\n`;
const seen = new Map();
for (const e of entries) {
  md += `## ${e.name} ${e.version}\n\n- License: ${e.license}\n- Source: ${e.url}\n\n`;
  for (const t of e.texts) {
    const key = t.text;
    if (seen.has(key)) {
      md += `${t.file}: identical to the text shown for ${seen.get(key)}.\n\n`;
    } else {
      seen.set(key, `${e.name} ${e.version}`);
      md += "```text\n" + t.text.replaceAll("```", "'''") + "\n```\n\n";
    }
  }
  if (e.texts.length === 0)
    md += "_No license file is included in the published package; the license is as declared above._\n\n";
}
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md.replaceAll("\r\n", "\n"));

const appVersion = JSON.parse(readFileSync(join(root, "src-tauri", "tauri.conf.json"), "utf8")).version;
const sbom = {
  bomFormat: "CycloneDX",
  specVersion: "1.5",
  version: 1,
  metadata: {
    component: { type: "application", name: "Devluma", version: appVersion, "bom-ref": "devluma" },
  },
  components: entries.map((e) => ({
    type: "library",
    name: e.name,
    version: e.version,
    purl: e.purl,
    "bom-ref": e.purl,
    licenses: [{ expression: e.license.replaceAll("/", " OR ") }],
    externalReferences: [{ type: "vcs", url: e.url }],
  })),
};
mkdirSync(join(root, "sbom"), { recursive: true });
writeFileSync(join(root, "sbom", "devluma.cdx.json"), JSON.stringify(sbom, null, 2) + "\n");

console.log(
  `${entries.length} components (${crates.length} cargo, ${npm.length} npm); ${missing.length} without a license file`,
);
if (missing.length) console.log("  without file:", missing.map((m) => `${m.name}@${m.version}`).join(", "));
